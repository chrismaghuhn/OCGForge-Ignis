    private static void TestPairedPublicWorldsAndFreshProcessValues()
    {
        OcgForgeLogicalModelInputV1 first = RequireLogical(
            CreateAcceptedDecision(CreateFrame(), CreateYesNoContext(), new[]
            {
                New<FlatYesNoPublicCandidateDescriptorV1>("world-a", FlatPromptChoiceKindV1.Yes)
            }));
        OcgForgeLogicalModelInputV1 second = RequireLogical(
            CreateAcceptedDecision(CreateFrame(), CreateYesNoContext(), new[]
            {
                New<FlatYesNoPublicCandidateDescriptorV1>("world-b", FlatPromptChoiceKindV1.Yes)
            }));
        OcgForgeCardVocabularyV1 vocabulary =
            OcgForgeCardVocabularyV1.TryCreate(new uint[] { 1001, 2002, 3003 }).Value!;
        OcgForgeEncodedModelInputV1 firstEncoded =
            OcgForgeEncodedModelInputBridgeV1.TryCreate(first, vocabulary).Value!;
        OcgForgeEncodedModelInputV1 secondEncoded =
            OcgForgeEncodedModelInputBridgeV1.TryCreate(second, vocabulary).Value!;
        string firstIdentity = OcgForgeModelInputIdentityV1.Create(first, firstEncoded, vocabulary);
        string secondIdentity = OcgForgeModelInputIdentityV1.Create(second, secondEncoded, vocabulary);
        Require(first.CanonicalBytes.SequenceEqual(second.CanonicalBytes) &&
                firstEncoded.CanonicalBytes.SequenceEqual(secondEncoded.CanonicalBytes) &&
                firstIdentity == secondIdentity,
            "equal public paired worlds did not produce equal I6E values");
        Console.WriteLine($"I6E_MODEL_INPUT_IDENTITY={firstIdentity}");
        Console.WriteLine($"I6E_LOGICAL_LENGTH={first.CanonicalBytes.Length}");
        Console.WriteLine($"I6E_ENCODED_LENGTH={firstEncoded.CanonicalBytes.Length}");
    }

