    private static void TestVocabularyNativeKatAndImmutability()
    {
        uint[] source = { 1001, 2002, 3003 };
        OcgForgeCardVocabularyResultV1 result =
            OcgForgeCardVocabularyV1.TryCreate(source);
        Require(result.IsSuccess && result.Value is not null,
            result.Error?.ToString() ?? "native vocabulary vector was rejected");

        OcgForgeCardVocabularyV1 vocabulary = result.Value!;
        Require(Convert.ToHexString(vocabulary.CanonicalBytes).ToLowerInvariant() ==
                NativeVocabularyCanonicalHex,
            "vocabulary canonical bytes differ from the independent native KAT");
        Require(vocabulary.Identity == NativeVocabularyIdentity,
            "vocabulary identity differs from the independent native KAT");
        Require(OcgForgeCardVocabularyV1.PadId == 0 &&
                OcgForgeCardVocabularyV1.UnknownOrRedactedId == 1 &&
                vocabulary.IdForPublicPasscode(1001) == 2 &&
                vocabulary.IdForPublicPasscode(3003) == 4 &&
                vocabulary.IdForPublicPasscode(9999) is null,
            "vocabulary reserved or ranked IDs are incorrect");

        source[0] = 9999;
        Require(vocabulary.AscendingPasscodes[0] == 1001,
            "vocabulary did not deep-copy the caller list");

        foreach (uint[] invalid in new[]
                 {
                     new uint[] { 0 },
                     new uint[] { 2002, 1001 },
                     new uint[] { 1001, 1001 }
                 })
        {
            OcgForgeCardVocabularyResultV1 rejected =
                OcgForgeCardVocabularyV1.TryCreate(invalid);
            Require(!rejected.IsSuccess && rejected.Value is null &&
                    rejected.Error?.Code ==
                        OcgForgeCardVocabularyErrorCodeV1.InvalidPasscodeList,
                "invalid vocabulary list was repaired instead of rejected");
        }
    }

    private static void TestMinimalNativeLogicalEncodedKat()
    {
        OcgForgePublicDecisionContextV1 decision =
            CreateAcceptedDecision(
                CreateMinimalFrame(),
                CreateYesNoContext(),
                new[]
                {
                    New<FlatYesNoPublicCandidateDescriptorV1>(
                        "native-minimal",
                        FlatPromptChoiceKindV1.No)
                });
        OcgForgeLogicalModelInputV1 logical = RequireLogical(decision);
        OcgForgeCardVocabularyV1 vocabulary =
            OcgForgeCardVocabularyV1.TryCreate(Array.Empty<uint>()).Value!;
        OcgForgeEncodedModelInputV1 encoded =
            OcgForgeEncodedModelInputBridgeV1.TryCreate(logical, vocabulary).Value!;

        Require(Convert.ToHexString(logical.CanonicalBytes).ToLowerInvariant() ==
                NativeMinimalLogicalHex,
            "logical canonical bytes differ from the pinned native model KAT");
        Require(Convert.ToHexString(encoded.CanonicalBytes).ToLowerInvariant() ==
                NativeMinimalEncodedHex,
            "encoded canonical bytes differ from the pinned native model KAT");
        byte[] identityBytes = OcgForgeModelInputIdentityV1.CanonicalModelInputIdentityBytes(
            logical,
            encoded);
        string identityDigest = Convert.ToHexString(
                SHA256.HashData(identityBytes)).ToLowerInvariant();
        Require(OcgForgeModelInputIdentityV1.Create(logical, encoded, vocabulary) ==
                NativeMinimalModelInputIdentity,
            "model-input identity differs from the pinned native model KAT");
        Require(identityDigest == NativeMinimalModelInputIdentity["model_input.v1.".Length..],
            "model-input identity bytes do not hash to the native KAT");
    }

    private static void TestFullAcceptedBoundaryBridge()
    {
        OcgForgeModelContractBundleV1 bundle = AcceptedBundle();
        OcgForgePublicDecisionContextV1 decision =
            CreateAcceptedDecision(CreateFrame(), CreateChainContext(), new[]
            {
                New<FlatChainPublicCandidateDescriptorV1>(
                    "local.chain",
                    0,
                    Locator("p0:MONSTER_ZONE:0"),
                    42UL,
                    (byte)0)
            });

        OcgForgeLogicalModelInputResultV1 logicalResult =
            OcgForgeLogicalModelInputBridgeV1.TryCreate(bundle, decision);
        Require(logicalResult.IsSuccess && logicalResult.Value is not null,
            logicalResult.Error?.ToString() ?? "accepted I6D boundary was rejected");
        OcgForgeLogicalModelInputV1 logical = logicalResult.Value!;

        Require(logical.SchemaIdValue == OcgForgeLogicalModelInputV1.SchemaId &&
                logical.PerspectivePlayer == 0 && logical.DecisionIndex == 0 &&
                logical.PublicObservationContextKind == "chain" &&
                logical.PublicObservationContextPlayer == 0 &&
                logical.CandidateFeatures.Count == 1 &&
                logical.CandidateRouting.Count == 1 &&
                logical.CandidateRouting[0].PublicActionKey ==
                    decision.Candidates[0].PublicActionKey,
            "logical top-level I6D fields are not bound exactly");
        Require(logical.PublicLocatorTable.Count >= 3 &&
                logical.ReferencedPublicEntities.Count == 1 &&
                logical.ReferencedPublicEntities[0].Value == "p0:MONSTER_ZONE:0" &&
                logical.PublicSafeState.Entities.Count == 3 &&
                logical.PublicSafeState.Relationships.Count == 1 &&
                logical.PublicSafeState.Chain.Links.Count == 1 &&
                logical.PublicSafeState.VisibleEvents.Count == 2,
            "logical safe state or locator table lost accepted public fields");
        Require(logical.PublicSafeState.VisibleEvents[0].Entity is { } eventEntity &&
                eventEntity.Locator.Value == "p0:MONSTER_ZONE:0" &&
                eventEntity.Locator.PublicLocatorOrdinal < logical.PublicLocatorTable.Count,
            "historical event reference did not use the shared locator table");

        OcgForgeCardVocabularyResultV1 vocabularyResult =
            OcgForgeCardVocabularyV1.TryCreate(new uint[] { 1001, 2002, 3003 });
        Require(vocabularyResult.IsSuccess && vocabularyResult.Value is not null,
            "full bridge vocabulary was rejected");
        OcgForgeCardVocabularyV1 vocabulary = vocabularyResult.Value!;
        OcgForgeEncodedModelInputResultV1 encodedResult =
            OcgForgeEncodedModelInputBridgeV1.TryCreate(logical, vocabulary);
        Require(encodedResult.IsSuccess && encodedResult.Value is not null,
            encodedResult.Error?.ToString() ?? "logical input was not encoded");
        OcgForgeEncodedModelInputV1 encoded = encodedResult.Value!;

        Require(encoded.CardVocabularyIdentity == vocabulary.Identity &&
                encoded.Entities.Any(entity => entity.IdentityKnown &&
                    entity.CardVocabularyId == 2) &&
                encoded.Entities.Any(entity => !entity.IdentityKnown &&
                    entity.CardVocabularyId == 1 && entity.Printed is null &&
                    entity.Current is null) &&
                encoded.VisibleEvents[0].PublicCardVocabularyId == 2 &&
                encoded.CandidateFeatures.Count == logical.CandidateFeatures.Count &&
                encoded.RoutingKeys.SequenceEqual(
                    logical.CandidateRouting.Select(value => value.PublicActionKey)),
            "encoded model input did not preserve vocabulary or N-to-N fields");
        OcgForgeEncodedEntityV1 encodedMonster = encoded.Entities.Single(
            entity => entity.PublicLocatorOrdinal == logical.PublicSafeState.Entities
                .Single(source => source.Card.Locator == "p0:MONSTER_ZONE:0")
                .PublicLocatorOrdinal);
        Require(encodedMonster.Current is not null &&
                encodedMonster.Current.LinkRating == 2 &&
                encodedMonster.Current.LinkMarkerCodes.SequenceEqual(new byte[] { 1, 4 }) &&
                encodedMonster.Current.Counters.SequenceEqual(
                    new[] { new OcgForgeEncodedCounterV1(7, 3) }),
            "encoded Current properties were not preserved exactly");

        OcgForgeModelInputIdentityResultV1 identity =
            OcgForgeModelInputIdentityV1.TryCreate(logical, encoded, vocabulary);
        Require(identity.IsSuccess && identity.Identity is not null &&
                identity.Identity.StartsWith("model_input.v1.", StringComparison.Ordinal) &&
                identity.Identity.Length == "model_input.v1.".Length + 64,
            identity.FieldPath ?? "model-input identity was rejected");
        Require(OcgForgeModelInputIdentityV1.CanonicalBytes(logical, encoded).Length >
                logical.CanonicalBytes.Length,
            "model-input identity did not bind both canonical inputs");
    }

    private static void TestCandidateNToNAndRouting()
    {
        PerspectiveSafeFrameV1 frame = CreateFrame();
        OcgForgePublicDecisionContextV1 decision =
            CreateAcceptedDecision(frame, New<FlatPromptOptionPublicContextV1>((byte)0), new[]
            {
                New<FlatOptionPublicCandidateDescriptorV1>("local.a", 0, 7UL),
                New<FlatOptionPublicCandidateDescriptorV1>("local.b", 1, 7UL),
                New<FlatOptionPublicCandidateDescriptorV1>("local.c", 2, 9UL)
            });
        OcgForgeLogicalModelInputResultV1 result =
            OcgForgeLogicalModelInputBridgeV1.TryCreate(AcceptedBundle(), decision);
        Require(result.IsSuccess && result.Value is not null,
            result.Error?.ToString() ?? "multiple accepted candidates were rejected");
        OcgForgeLogicalModelInputV1 logical = result.Value!;
        Require(logical.CandidateFeatures.Count == 3 &&
                logical.CandidateRouting.Count == 3 &&
                logical.CandidateFeatures[0].Choice?.ResponseIndex == 0 &&
                logical.CandidateFeatures[1].Choice?.ResponseIndex == 1 &&
                logical.CandidateFeatures[2].Choice?.ResponseIndex == 2 &&
                logical.CandidateRouting[0].PublicActionKey == decision.Candidates[0].PublicActionKey &&
                logical.CandidateRouting[1].PublicActionKey == decision.Candidates[1].PublicActionKey &&
                logical.CandidateRouting[2].PublicActionKey == decision.Candidates[2].PublicActionKey,
            "candidate N-to-N order or routing alignment changed");

        OcgForgePublicDecisionContextV1 equivalent =
            CreateAcceptedDecision(frame, New<FlatPromptOptionPublicContextV1>((byte)0), new[]
            {
                New<FlatOptionPublicCandidateDescriptorV1>("other.a", 0, 7UL),
                New<FlatOptionPublicCandidateDescriptorV1>("other.b", 1, 7UL),
                New<FlatOptionPublicCandidateDescriptorV1>("other.c", 2, 9UL)
            });
        OcgForgeLogicalModelInputResultV1 equivalentResult =
            OcgForgeLogicalModelInputBridgeV1.TryCreate(AcceptedBundle(), equivalent);
        Require(equivalentResult.IsSuccess && equivalentResult.Value is not null &&
                logical.CanonicalBytes.SequenceEqual(equivalentResult.Value.CanonicalBytes),
            "Ignis-local candidate keys affected logical model identity");
    }

    private static void TestOptionalPresenceAndHistoricalReferences()
    {
        PerspectiveSafeFrameV1 absentFrame = CreateFrame(turnPlayer: null);
        PerspectiveSafeFrameV1 presentFrame = CreateFrame(turnPlayer: 0);
        OcgForgePublicDecisionContextV1 absentDecision =
            CreateAcceptedDecision(absentFrame, CreateYesNoContext(), new[]
            {
                New<FlatYesNoPublicCandidateDescriptorV1>("absent", FlatPromptChoiceKindV1.No)
            });
        OcgForgePublicDecisionContextV1 presentDecision =
            CreateAcceptedDecision(presentFrame, CreateYesNoContext(), new[]
            {
                New<FlatYesNoPublicCandidateDescriptorV1>("present", FlatPromptChoiceKindV1.No)
            });
        OcgForgeLogicalModelInputV1 absent = RequireLogical(absentDecision);
        OcgForgeLogicalModelInputV1 present = RequireLogical(presentDecision);

        Require(absent.PublicSafeState.Globals.TurnPlayer is null &&
                present.PublicSafeState.Globals.TurnPlayer == 0 &&
                !absent.CanonicalBytes.SequenceEqual(present.CanonicalBytes),
            "ABSENT and PRESENT(0) were collapsed in the logical codec");
        OcgForgeEncodedModelInputV1 absentEncoded =
            OcgForgeEncodedModelInputBridgeV1.TryCreate(
                absent,
                OcgForgeCardVocabularyV1.TryCreate(new uint[] { 1001, 2002, 3003 }).Value!)
                .Value!;
        OcgForgeEncodedModelInputV1 presentEncoded =
            OcgForgeEncodedModelInputBridgeV1.TryCreate(
                present,
                OcgForgeCardVocabularyV1.TryCreate(new uint[] { 1001, 2002, 3003 }).Value!)
                .Value!;
        Require(absentEncoded.Globals.TurnPlayer is null &&
                presentEncoded.Globals.TurnPlayer == 0 &&
                !absentEncoded.CanonicalBytes.SequenceEqual(presentEncoded.CanonicalBytes),
            "ABSENT and PRESENT(0) were collapsed in the encoded codec");
        Require(absent.PublicSafeState.VisibleEvents[0].Entity is { } eventEntity &&
                eventEntity.Locator.PublicLocatorOrdinal < absent.PublicLocatorTable.Count,
            "historical reference did not use the shared locator table");
        Require(absent.PublicSafeState.Relationships[0].Source.CurrentEntityOrdinal is not null &&
                absent.PublicSafeState.Relationships[0].Source.CurrentEntityOrdinal == 1,
            "current relationship reference did not resolve to the entity ordinal");
    }

    private static void TestContinuationSubmissionMetadata()
    {
        PerspectiveSafeFrameV1 frame = CreateFrame();
        PublicSemanticLocatorV1 source = Locator("p0:MONSTER_ZONE:0");
        FlatPromptCardSelectionPublicContextV1 context =
            New<FlatPromptCardSelectionPublicContextV1>((byte)0, 1U, 2U, false);
        OcgForgePublicDecisionContextV1 continuation =
            CreateAcceptedDecision(frame, context, new[]
            {
                New<FlatPromptCardSelectionLocatorCandidateV1>(
                    "local.pick",
                    0,
                    source)
            });
        OcgForgeLogicalModelInputV1 pick = RequireLogical(continuation);
        Require(pick.CandidateFeatures[0].ContinuationOperation == "pick" &&
                !pick.CandidateFeatures[0].SubmitsEngineResponse,
            "accepted intermediate continuation was marked terminal");

