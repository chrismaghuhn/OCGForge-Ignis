            });
        OcgForgeLogicalModelInputV1 terminal = RequireLogical(finish);
        Require(terminal.CandidateFeatures[0].ContinuationOperation == "finish" &&
                terminal.CandidateFeatures[0].SubmitsEngineResponse,
            "accepted terminal continuation was marked intermediate");
    }

