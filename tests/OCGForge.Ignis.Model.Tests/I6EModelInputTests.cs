    private static OcgForgePublicDecisionContextV1 CreateAcceptedDecision(
        PerspectiveSafeFrameV1 frame,
        FlatPromptPublicContextV1 context,
        IReadOnlyList<FlatPublicCandidateDescriptorV1> candidates)
    {
        FlatPromptProjectionResultV1 projection = New<FlatPromptProjectionResultV1>(
            true,
            FlatPromptErrorCodeV1.None,
            context,
            candidates);
        OcgForgeAcceptedDecisionBoundaryProducerV1 producer = new();
        Require(producer.TryAccept(
                frame,
                projection,
                out OcgForgeAcceptedDecisionBoundaryV1? accepted,
                out OcgForgeAcceptedDecisionBoundaryProducerErrorV1? error) &&
            accepted is not null,
            error?.ToString() ?? "accepted decision boundary was rejected");
        OcgForgePublicDecisionContextResultV1 result =
            OcgForgePublicCandidateBridgeV1.TryCreate(accepted);
        Require(result.IsSuccess && result.Context is not null,
            result.Error?.ToString() ?? "I6D public decision context was rejected");
        return result.Context!;
    }

